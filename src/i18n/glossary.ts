// The agreed translation of every term that must read the same everywhere in a language:
// the three band names, the five measure names, the group and category labels, "How the
// score works", "Deposit Pension Scheme (DPS)" and "Arthik". Translators use these exactly;
// messages.test.ts checks that the message files do. English is the source and is not here.
//
// Conventions that hold in every language:
//  - Brand and product names (bKash, Nagad, Foodpanda, Sanchayapatra where kept) stay as they are.
//  - "DPS" stays as the abbreviation inside the full name.
//  - `categoryProse` is the sentence form of a label that joins two ideas with "&" in English
//    ("Rent & housing" -> "Rent and housing"). It never contains "&".

